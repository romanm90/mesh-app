CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(500) NOT NULL,
                       date_of_birth DATE NOT NULL,
                       password_hash VARCHAR(500) NOT NULL
);

CREATE TABLE account (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL UNIQUE,
                         balance DECIMAL(19, 2) NOT NULL,
                         initial_balance DECIMAL(19, 2) NOT NULL,

                         CONSTRAINT fk_account_user
                             FOREIGN KEY (user_id) REFERENCES users(id),

                         CONSTRAINT chk_account_balance_nonnegative
                             CHECK (balance >= 0),

                         CONSTRAINT chk_account_initial_balance_nonnegative
                             CHECK (initial_balance >= 0)
);

CREATE TABLE email_data (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT NOT NULL,
                            email VARCHAR(200) NOT NULL,

                            CONSTRAINT fk_email_user
                                FOREIGN KEY (user_id) REFERENCES users(id),

                            CONSTRAINT uq_email
                                UNIQUE (email)
);

CREATE INDEX idx_email_user_id ON email_data(user_id);

CREATE TABLE phone_data (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT NOT NULL,
                            phone VARCHAR(13) NOT NULL,

                            CONSTRAINT fk_phone_user
                                FOREIGN KEY (user_id) REFERENCES users(id),

                            CONSTRAINT uq_phone
                                UNIQUE (phone),

                            CONSTRAINT chk_phone_format
                                CHECK (phone ~ '^7[0-9]{10}$')
);

CREATE INDEX idx_phone_user_id ON phone_data(user_id);
